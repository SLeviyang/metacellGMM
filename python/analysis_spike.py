    wide_sd = df.pivot(index=id_cols, columns="method", values="sd").reset_index()

    plotted_datasets = sorted(wide_mean["dataset"].unique())
    cmap = plt.get_cmap("tab10")
    colors = {dataset: cmap(i % 10) for i, dataset in enumerate(plotted_datasets)}

    # panels follow SPIKE_METHODS, minus any method the df has no rows for
    # (an older pkl that predates it) -- dropped rather than drawn empty
