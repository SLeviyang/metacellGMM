    color_norm = plt.Normalize(vmin=0, vmax=max(k - 1, 1))

    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    for ax, label in zip(axes, ["nb", "perm", "true"]):
        for i in range(k):
            mean_i, std_i = means[i], stds[i]
            color = cmap(color_norm(i))

            # the eigenvector (and hence its PC score) is only defined up to
            # an overall sign; the analytic mean stays fixed, so flip this
            # eigenvector's sign if that fits the analytic GMM better
            pc_scores = specs[label]["U"][:, i] * specs[label]["sv"][i]
            group_scores = pc_scores[mask]
            emp_mean = group_scores.mean()
            if abs(emp_mean - mean_i) > abs(-emp_mean - mean_i):
                group_scores = -group_scores

            ax.hist(group_scores, bins=30, density=True, histtype="step",
                    color=color, linewidth=1)

            x_grid = np.linspace(mean_i - 4 * std_i, mean_i + 4 * std_i, 300)
            ax.plot(x_grid, norm.pdf(x_grid, mean_i, std_i),
                    color=color, linewidth=1.5, linestyle="--")

        ax.set_xlabel("PC score")
        ax.set_ylabel("density")
        ax.set_title(f"{dataset} HVG {n_genes}, mixture {mixture_label}: {label}")

    fig.tight_layout()

    sm = plt.cm.ScalarMappable(cmap=cmap, norm=color_norm)
    sm.set_array([])
    fig.colorbar(sm, ax=axes, label="PC index", fraction=0.02, pad=0.02)

    # share x/y scale across panels; each panel's own autoscale already had
    # to fit every PC's +/-4*sd analytic window, so the union across panels
    # is guaranteed to include every PC's window in every panel
    x_lims = [ax.get_xlim() for ax in axes]
    y_lims = [ax.get_ylim() for ax in axes]
    shared_xlim = (min(lo for lo, _ in x_lims), max(hi for _, hi in x_lims))
    shared_ylim = (min(lo for lo, _ in y_lims), max(hi for _, hi in y_lims))
    for ax in axes:
        ax.set_xlim(shared_xlim)
        ax.set_ylim(shared_ylim)

    plt.show()
    return fig


