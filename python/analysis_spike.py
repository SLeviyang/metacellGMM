            y_lo, y_hi = wide[method].quantile([0.02, 0.98])
            panel = wide[wide["analytic"].between(x_lo, x_hi) & wide[method].between(y_lo, y_hi)]

            for dataset in plotted_datasets:
                sub = panel[panel["dataset"] == dataset]
                ax.scatter(sub["analytic"], sub[method], color=colors[dataset],
                          label=dataset, alpha=0.5, s=10)

