    for row, (wide, value_label, signed) in enumerate(row_specs):
        for col, method in enumerate(panels):
            ax = axes[row, col]

            # drop points whose x (analytic) or y (method) value falls in
            # the upper/lower 2% quantile of that panel's own x or y column,
