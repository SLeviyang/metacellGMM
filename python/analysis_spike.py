def compute_analytic_mixture_axes(pca_theory, mixture_labels, k, random_basis=False):
    """Per-mixture analytic mean, PC-score covariance eigenbasis, and the
    mean/sd expressed along that eigenbasis.

    For each mixture label, M_sv (the k x k analytic covariance of the PC
    scores U*sv, from get_GMM) is diagonalized M_sv = Q @ diag(eigvals) @ Q.T
    with Q orthogonal and eigvals sorted descending (so axis 0 is still the
    highest-variance direction, matching the old raw-PC-axis convention).

    If random_basis is True, Q is instead a freshly drawn random orthogonal
    k x k matrix (via QR decomposition of a random Gaussian matrix) rather
    than M_sv's eigenvectors -- there is no eigenvalue to sort by in that
    case, so the sd along each of its columns is computed with the general
    quadratic form diag(Q.T @ M_sv @ Q), which is equivalent to sqrt(eigvals)
    when Q is the eigenvector basis but also valid for an arbitrary
    orthogonal Q.

    Returns five lists aligned with mixture_labels:
    - means: raw (unrotated) first-k GMM mean vectors -- kept around because
      determine_axis_signs needs to compare against other methods' raw means
      before anyone is rotated (see determine_axis_signs).
    - Qs: the k x k orthogonal basis matrices.
    - rotated_means: means projected onto Q's columns (Q.T @ mean).
    - rotated_sds: the analytic sd along Q's columns.
    - covariances: M_sv itself (raw, unrotated k x k analytic covariance) --
      kept around as the W_a reference for compute_rotated_empirical_moments's
      independence metric.
    """
    means = []
    Qs = []
    rotated_means = []
    rotated_sds = []
    covariances = []
    for label in mixture_labels:
        gmm = lwa.get_GMM(pca_theory, label)
        mean = np.asarray(gmm["mean"])[:k]
        M_sv = np.asarray(gmm["covariance"])[:k, :k]

        if random_basis:
            Q, _ = np.linalg.qr(np.random.randn(k, k))
            rotated_sd = np.sqrt(np.clip(np.diag(Q.T @ M_sv @ Q), 0, None))
        else:
            eigvals, Q = np.linalg.eigh(M_sv)
            order = np.argsort(eigvals)[::-1]
            eigvals, Q = eigvals[order], Q[:, order]
            rotated_sd = np.sqrt(np.clip(eigvals, 0, None))

        means.append(mean)
        Qs.append(Q)
        rotated_means.append(Q.T @ mean)
        rotated_sds.append(rotated_sd)
        covariances.append(M_sv)
    return means, Qs, rotated_means, rotated_sds, covariances


def determine_axis_signs(spec, cell_labels, mixture_labels, k, analytic_means):
    """Length-k array of +-1, one per raw (unrotated) PC axis, chosen so that
    this method's raw per-mixture mean best matches the analytic raw
    per-mixture mean (`analytic_means`, aligned with mixture_labels -- see
    compute_analytic_mixture_axes), pooling the sign choice across all
    mixture labels since a PC's eigenvector has a single sign for the whole
    dataset, not one free per mixture.

    This must run, and be applied, before projecting through a mixture's Q
    (see compute_rotated_empirical_moments): once axes are mixed by a
    rotation, a wrong sign on one input axis corrupts every rotated
    coordinate, not just the one it started on, so a post-hoc scalar sign
    flip on the rotated output can no longer undo it.
    """
    pc_scores = spec["U"][:, :k] * spec["sv"][:k]
    raw_means = np.zeros((len(mixture_labels), k))
    for m, label in enumerate(mixture_labels):
        mask = cell_labels == label
        raw_means[m, :] = pc_scores[mask, :].mean(axis=0)

    analytic = np.asarray(analytic_means)
    # sign that maximizes sum(sign * mean * analytic_mean), i.e. minimizes
    # sum((sign * mean - analytic_mean)**2) over sign in {+1, -1}, pooled
    # across mixture labels (axis 0)
    dot = (raw_means * analytic).sum(axis=0)
    return np.where(dot >= 0, 1.0, -1.0)


def compute_rotated_empirical_moments(spec, cell_labels, mixture_labels, k, sign, Qs,
                                       analytic_covariances):
    """Empirical mean, std, normality, and independence for this method,
    each mixture's PC scores projected into that mixture's own analytic
    covariance eigenbasis (Qs, aligned with mixture_labels -- see
    compute_analytic_mixture_axes).

    `sign` (from determine_axis_signs) is applied to the raw PC axes before
    rotating through Q, resolving this method's SVD sign ambiguity against
    the analytic axes.

    `normality` is the max absolute difference between the empirical CDF and
    the CDF of a normal distribution fit to that same rotated sample's
    mean/std -- see normality.max_ecdf_normal_diff.

    `independence` is ||W - W_a|| / ||W_a|| (Frobenius norm), where W is this
    method's empirical k x k covariance matrix of (sign-corrected) U*sv for
    that mixture's cells, and W_a is analytic_covariances[mixture_idx] (M_sv,
    from compute_analytic_mixture_axes) -- how far this method's whole
    covariance structure is from the analytic model's prediction for that
    mixture, as a fraction of the analytic covariance's own size. This is
    computed on the raw (unrotated) sign-corrected scores rather than the
    Q-rotated ones -- a Frobenius norm is invariant to rotating both W and
    W_a by the same orthogonal Q, so the value is identical either way, but
    sign correction still matters here (unlike the rotation): W_a sits in
    analytic's own fixed sign convention, while a method's raw axes have an
    arbitrary SVD sign with no reason to match it, and (unlike variances) the
    off-diagonal covariance entries flip sign with a mismatched axis sign. It
    is a joint property of the whole covariance matrix, so it is the same
    value for all k rows of a given mixture.

    Returns four flat arrays aligned with itertools.product(mixture_labels, range(k)).
    """
    # local import: normality imports this module at top level, so a
    # top-level import here would be circular
    import normality as nrm

    pc_scores = spec["U"][:, :k] * spec["sv"][:k] * sign[np.newaxis, :]

    means, stds, normality, independence = [], [], [], []
    for label, Q, W_a in zip(mixture_labels, Qs, analytic_covariances):
        mask = cell_labels == label
        rotated = pc_scores[mask, :] @ Q

        W = np.cov(pc_scores[mask, :], rowvar=False)
        indep = np.linalg.norm(W - W_a, ord="fro") / np.linalg.norm(W_a, ord="fro")

        for j in range(k):
            group = rotated[:, j]
            mean_j, std_j = group.mean(), group.std()
            means.append(mean_j)
            stds.append(std_j)
            normality.append(nrm.max_ecdf_normal_diff(group, mean_j, std_j))
            independence.append(indep)
    return np.array(means), np.array(stds), np.array(normality), np.array(independence)


def build_spike_moments_df(dataset_names=datasets.DEFAULT_DATASETS, n_genes_list=datasets.DEFAULT_N_GENES,
                            random_basis=False, refined=False):
    """Long-format table of GMM/empirical mean, standard deviation, and
    normality, each measured along the analytic covariance's own principal
    axes rather than the raw PCA axes.

    For each (dataset, n_genes, mixture_label), the analytic PC-score
    covariance M_sv is diagonalized as Q @ diag(eigvals) @ Q.T (see
    compute_analytic_mixture_axes); every method's per-cell PC scores
    (sign-corrected against the analytic raw axes first -- see
    determine_axis_signs) are projected onto Q's columns before mean/sd/
    normality/independence are computed (see compute_rotated_empirical_moments).
    So "pca_idx" here indexes a mixture-specific rotated axis (0 = highest
    analytic variance for that mixture), not a direction shared across
    mixture labels the way the raw PCA axes were.

    If random_basis is True, Q is a random orthogonal matrix instead of
    M_sv's eigenvectors (see compute_analytic_mixture_axes) -- "pca_idx"
    then just indexes one of k random orthogonal directions per mixture,
    with no eigenvalue ordering behind it.

    One row per (dataset, n_genes, mixture_label, pca_idx, method), with
    method in {"analytic", "normal", "nb", "perm", "true"}. mixture_label/pca_idx are
    kept (beyond dataset/n_genes/method/mean/sd/normality/independence) so that
    rows can be re-aligned across methods later (e.g. pivoted to plot
    nb/perm/true vs analytic).

    `normality` is the max absolute difference between the empirical CDF and
    a fitted normal CDF (see normality.max_ecdf_normal_diff); it is trivially 0 for
    "analytic" rows since the analytic theory is assumed exactly Gaussian.

    `independence` is ||W - W_a|| / ||W_a|| (Frobenius norm), the relative
    distance between this method's empirical k x k covariance matrix of
    (sign-corrected) U*sv for that mixture and the analytic covariance M_sv
    predicts for it (see compute_rotated_empirical_moments). It is a joint
    property of the whole covariance matrix for a given mixture, so it is
    constant across pca_idx within a (dataset, n_genes, mixture_label,
    method) group; it is trivially 0 for "analytic" rows since W = W_a there
    by construction.
    """
    rows = []
    for dataset in dataset_names:
        for n_genes in n_genes_list:
            if not has_spike_result(dataset, n_genes, refined=refined):
                continue

            result = load_spike_result(dataset, n_genes, refined=refined)

            # the h5ad must come from the same partition as the pkl -- the
            # cell labels below are matched against it row for row
            s = (dr.load_HVG_refined_dataset(dataset, n_genes) if refined
                 else datasets.load_HVG_dataset(dataset, n_genes))
            cell_labels = s.obs["metacell"].to_numpy()
            mixture_labels = np.unique(cell_labels)
            k = result["spec_nb"]["U"].shape[1]

            analytic_means, Qs, analytic_rotated_means, analytic_rotated_sds, analytic_covariances = (
                compute_analytic_mixture_axes(result["pca_theory"], mixture_labels, k, random_basis))

            # a second, independent draw from the same analytic GMM (same
            # mean/covariance as the analytic model, fresh randomness), to see
            # how much of the reference normality/independence is sampling noise.
            # Rows already come out in cell_labels order (see
            # simulate_PCA_embedding), so no realignment is needed here.
            pca_theory = result["pca_theory"]
            spec_gmm_resampled = lwa.simulate_PCA_embedding(pca_theory, cell_labels)

            # driven by SPIKE_METHODS rather than a local list, so a method
            # added there (e.g. the pert_* perturbed-covariance draws) flows
            # into the moments df and its plots. A pkl written before a method
            # existed simply lacks the key and is skipped, so stale pkls still
            # work -- they just contribute no rows for that method.
            specs = {m: result[SPEC_KEYS[m]] for m in SPIKE_METHODS
                     if SPEC_KEYS[m] in result}
            missing = [m for m in SPIKE_METHODS if SPEC_KEYS[m] not in result]
            if missing:
                print(f"  {dataset}/{n_genes}: no {', '.join(missing)} in this pkl "
                      f"(rebuild with overwrite=True to add)")
            specs["gmm_resampled"] = spec_gmm_resampled
            empirical_moments = {}
            for method, spec in specs.items():
                sign = determine_axis_signs(spec, cell_labels, mixture_labels, k, analytic_means)
                empirical_moments[method] = compute_rotated_empirical_moments(
                    spec, cell_labels, mixture_labels, k, sign, Qs, analytic_covariances)

            idx = 0
            for mixture_idx, mixture_label in enumerate(mixture_labels):
                for pca_idx in range(k):
                    moments_by_method = {"analytic": (analytic_rotated_means[mixture_idx][pca_idx],
                                                        analytic_rotated_sds[mixture_idx][pca_idx], 0.0, 0.0),
                                        **{method: (means[idx], stds[idx], normality[idx], independence[idx])
                                           for method, (means, stds, normality, independence)
                                           in empirical_moments.items()}}
                    for method, (mean, sd, normality_val, independence_val) in moments_by_method.items():
                        rows.append({"dataset": dataset, "n_genes": n_genes,
                                    "mixture_label": mixture_label, "pca_idx": pca_idx,
                                    "method": method, "mean": mean, "sd": sd,
                                    "normality": normality_val, "independence": independence_val})
                    idx += 1

    return pd.DataFrame(rows)


