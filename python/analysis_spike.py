# spike pkls are split by provenance the same way the HVG h5ads they are
# built from are: refined ones come from analysis_HVG_refined, unrefined
# from analysis_HVG
SPIKE_DIR = "../analysis_spike/"
SPIKE_REFINED_DIR = "../analysis_spike_refined/"

# normal/nb/perm/true come from a genuine SVD of an (n_cells x n_genes)
# matrix, and so have right singular vectors. `analytic` is deliberately not
# among them: it is the reference the others are compared against, and its
# spec_analytic is built from pca_theory rather than decomposed.
#
# <base>_proj_i are simulated rather than decomposed: the analytic model's
# metacell moments projected onto that base method's basis, with a rank-i PSD
# correction fitted against the base's own empirical covariances, then sampled
# one cell per row (see anndata2spike). perm is the permutation null and true
# is the real data, so the two series show how much of each basis's covariance
# structure the model plus i correction directions reproduces. They carry no V
# -- there is no gene-space decomposition behind them -- so they can be
# consumed anywhere a spec's U*sv scores are used, but cannot serve as a
# projection basis.
PROJ_RANKS = [0, 1, 2, 3]
PROJ_BASES = ["perm", "true"]
PROJ_METHODS = [f"{base}_proj_{i}" for base in PROJ_BASES for i in PROJ_RANKS]
SPIKE_METHODS = ["normal", "nb", "perm", "true"] + PROJ_METHODS
SPEC_KEYS = {"normal": "spec_n", "nb": "spec_nb",
             "perm": "spec_perm", "true": "spec_true"}
SPEC_KEYS.update({m: f"spec_{m}" for m in PROJ_METHODS})


